"""Password, card fingerprint, CSRF, and request validation helpers."""

from __future__ import annotations

import base64
import hashlib
import hmac
import re
import secrets
from typing import Any
from urllib.parse import urlsplit


USERNAME_RE = re.compile(r"^[A-Za-z0-9_]{4,32}$")
GROUP_ID_RE = re.compile(r"^\d{5,20}$")
EMAIL_RE = re.compile(r"^[^\s@]{1,64}@[^\s@]{1,255}$")
PASSWORD_SCHEME = "scrypt_v1"
# A domain-separated proof used only by the Windows-to-portal sync handshake.
# It proves that both ends were configured with the same card-fingerprint
# pepper without sending either the pepper or a raw license card over HTTPS.
CARD_PEPPER_PROOF_CONTEXT = b"joker-portal-card-pepper-proof-v1"
# Match only cards generated by the Windows plugin.  Keeping the grammar here
# avoids importing the plugin runtime into the Linux-only portal package.
CARD_RE = re.compile(
    r"^JK(?:-1-\d{13}[0-9A-F]{12}|[1-9]\d*-\d{13}[0-9A-F]{12}|[1-9]\d*\d{13}[0-9A-F]{12})$"
)
GAME_CARD_RE = re.compile(
    r"^JG(?:-1-\d{13}[0-9A-F]{12}|[1-9]\d*-\d{13}[0-9A-F]{12})$"
)


def normalize_username(value: str) -> str:
    return (value or "").strip().lower()


def validate_username(value: str) -> str:
    username = normalize_username(value)
    if not USERNAME_RE.fullmatch(username):
        raise ValueError("账号只能包含字母、数字和下划线，长度为 4-32 位")
    return username


def normalize_email(value: str) -> str:
    return (value or "").strip().lower()


def validate_email(value: str) -> str:
    """Validate a practical mailbox address without attempting DNS delivery."""
    email = normalize_email(value)
    if not EMAIL_RE.fullmatch(email) or ".." in email.split("@", 1)[1]:
        raise ValueError("请输入正确的邮箱地址")
    return email


def validate_password(value: str) -> str:
    password = value or ""
    if len(password) < 8 or len(password) > 128:
        raise ValueError("密码长度必须为 8-128 位")
    if password.isspace():
        raise ValueError("密码不能全部为空白字符")
    return password


def validate_group_id(value: str) -> str:
    group_id = (value or "").strip()
    if not GROUP_ID_RE.fullmatch(group_id):
        raise ValueError("请输入正确的 QQ 群号（5-20 位数字）")
    return group_id


def validate_root_relative_redirect(value: str) -> str:
    """Reject external redirect targets before they reach ``Location``.

    A root-relative location makes the browser retain the public domain from
    the original request.  In particular, it cannot expose a reverse proxy's
    origin IP through an absolute or protocol-relative redirect.
    """
    if not isinstance(value, str) or not value.startswith("/") or "\\" in value:
        raise ValueError("redirect target must be a root-relative path")
    parsed = urlsplit(value)
    if parsed.scheme or parsed.netloc or value.startswith("//"):
        raise ValueError("redirect target must not include a scheme or host")
    return value


def normalize_card(value: str) -> str:
    card = re.sub(r"\s+", "", value or "").upper()
    if len(card) > 96 or not CARD_RE.fullmatch(card):
        raise ValueError("卡密格式不正确")
    return card


def normalize_game_card(value: str) -> str:
    """Normalize a game/WebSocket card without accepting a QQ card."""
    card = re.sub(r"\s+", "", value or "").upper()
    if len(card) > 96 or not GAME_CARD_RE.fullmatch(card):
        raise ValueError("游戏卡密格式不正确")
    return card


def hash_password(password: str) -> str:
    password = validate_password(password)
    salt = secrets.token_bytes(16)
    derived = hashlib.scrypt(
        password.encode("utf-8"), salt=salt, n=2**14, r=8, p=1, dklen=32
    )
    return "$".join(
        (
            PASSWORD_SCHEME,
            base64.urlsafe_b64encode(salt).decode("ascii"),
            base64.urlsafe_b64encode(derived).decode("ascii"),
        )
    )


def verify_password(password: str, stored_hash: str) -> bool:
    try:
        scheme, encoded_salt, encoded_hash = stored_hash.split("$", 2)
        if scheme != PASSWORD_SCHEME:
            return False
        salt = base64.urlsafe_b64decode(encoded_salt.encode("ascii"))
        expected = base64.urlsafe_b64decode(encoded_hash.encode("ascii"))
        actual = hashlib.scrypt(
            (password or "").encode("utf-8"),
            salt=salt,
            n=2**14,
            r=8,
            p=1,
            dklen=len(expected),
        )
        return hmac.compare_digest(actual, expected)
    except (ValueError, TypeError):
        return False


def card_fingerprint(card: str, pepper: str) -> str:
    return hmac.new(
        pepper.encode("utf-8"), normalize_card(card).encode("utf-8"), hashlib.sha256
    ).hexdigest()


def game_card_fingerprint(card: str, pepper: str) -> str:
    return hmac.new(
        pepper.encode("utf-8"),
        normalize_game_card(card).encode("utf-8"),
        hashlib.sha256,
    ).hexdigest()


def card_pepper_proof(pepper: str) -> str:
    """Return a non-reversible proof that a sync client has the portal pepper.

    The bearer sync token still authenticates the request.  This additional
    proof exists to fail closed when the Windows plugin is configured with an
    empty or different ``card_pepper``; without it, configuration sync can
    appear healthy while every card claim silently fails to match.
    """
    normalized = str(pepper or "").strip()
    return hmac.new(
        normalized.encode("utf-8"), CARD_PEPPER_PROOF_CONTEXT, hashlib.sha256
    ).hexdigest()


def mask_card(card: str) -> str:
    try:
        normalized = normalize_card(card)
    except ValueError:
        # Displaying old audit data must not make an administrator listing
        # fail.  It remains visibly masked and cannot be used for a claim.
        normalized = re.sub(r"\s+", "", card or "").upper()
        if not normalized:
            return ""
    if len(normalized) <= 12:
        return normalized[:4] + "****" + normalized[-2:]
    return normalized[:7] + "****" + normalized[-5:]


def ensure_csrf_token(session: dict[str, Any]) -> str:
    token = session.get("csrf_token")
    if not isinstance(token, str) or len(token) < 32:
        token = secrets.token_urlsafe(32)
        session["csrf_token"] = token
    return token


def valid_csrf(session: dict[str, Any], supplied: str | None) -> bool:
    expected = session.get("csrf_token", "")
    return bool(expected and supplied and hmac.compare_digest(str(expected), str(supplied)))
